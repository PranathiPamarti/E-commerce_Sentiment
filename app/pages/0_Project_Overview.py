import json
from pathlib import Path

import pandas as pd
import streamlit as st


PROJECT_ROOT = Path(__file__).resolve().parents[2]
STATS_PATH = PROJECT_ROOT / "data" / "review_intelligence_stats.json"
METRICS_PATH = PROJECT_ROOT / "models" / "review_sentiment_metrics.json"
SCORED_PATH = PROJECT_ROOT / "data" / "review_intelligence_scored.parquet"
AUDIT_PATH = PROJECT_ROOT / "data" / "issue_tag_annotations.csv"

st.title("E-Commerce Review Intelligence")
st.markdown(
    "A review-analysis workflow for understanding product feedback at portfolio, "
    "product, and reviewer levels."
)
st.markdown(
    "Start with **Dataset and data quality**, then **Sentiment model**, followed "
    "by **Issues and products**. The audit page shows what still needs human "
    "validation. Synthetic examples are separated in the sidebar."
)

if not STATS_PATH.is_file() or not METRICS_PATH.is_file():
    st.warning(
        "The main analysis artifacts are not ready. Run "
        "`python -m src.prepare_review_intelligence` and then "
        "`python -m src.train_review_sentiment` from the project root."
    )
    st.stop()

stats = json.loads(STATS_PATH.read_text(encoding="utf-8"))
metrics = json.loads(METRICS_PATH.read_text(encoding="utf-8"))
test_metrics = metrics["held_out_test_metrics"]
prediction_total = metrics["out_of_time_prediction_counts"]["total"]
review_products = stats["products"]
test_neutral_f1 = test_metrics["classification_report"]["neutral"]["f1-score"]

summary_columns = st.columns(4)
summary_columns[0].metric("Reviews prepared", f"{stats['reviews']:,}")
summary_columns[1].metric("Products", f"{stats['products']:,}")
summary_columns[2].metric("Reviewers", f"{stats['reviewers']:,}")
summary_columns[3].metric("Out-of-time sentiment scores", f"{prediction_total:,}")

st.subheader("What the ML pipeline does")
st.write(
    "The main review-intelligence model is one three-class TF-IDF + balanced "
    "SGD text classifier. It predicts labels derived from star ratings, using a "
    "chronological train/tune/validation/test design. The held-out test contains "
    f"{metrics['test_rows']:,} reviews and scores {test_metrics['accuracy']:.1%} "
    f"accuracy with {test_metrics['macro_f1']:.3f} macro-F1 against those "
    "rating-derived labels."
)
st.caption(
    f"Neutral-class F1 is {test_neutral_f1:.3f}. These results are not an "
    "independent human-sentiment evaluation."
)

st.subheader("How many models are in the project?")
model_summary = pd.DataFrame(
    [
        {
            "Component": "Review-intelligence sentiment",
            "Method": "TF-IDF + balanced SGDClassifier (3 classes)",
            "Role": "Main All_Beauty text model; one final saved pipeline",
            "Training": "2 regularization candidates, then selected model refit",
        },
        {
            "Component": "Synthetic-demo sentiment",
            "Method": "TF-IDF + logistic regression (2 classes)",
            "Role": "Separate legacy demo on synthetic review records",
            "Training": "Logistic regression vs MultinomialNB, then refit winner",
        },
        {
            "Component": "Recommendation prototype",
            "Method": "Generator-provided latent factors + optional description similarity",
            "Role": "Synthetic demonstration only",
            "Training": "Factors are generated by the simulator, not learned from reviews",
        },
    ]
)
st.dataframe(model_summary, hide_index=True, width="stretch")
st.info(
    "The primary sentiment training command fits two alpha candidates and one "
    "final refit (three fit calls), then saves one final model. Opening the main "
    "dashboard does not retrain it; it reads persisted scored data and metrics. "
    "The issue tags are rules, not a trained model."
)

st.subheader("What is established—and what is not")
left, right = st.columns(2)
with left:
    st.markdown("**Measured in this run**")
    st.write(
        f"- {stats['reviews']:,} valid sampled reviews across {review_products:,} products.\n"
        f"- {prediction_total:,} validation/test-period sentiment predictions.\n"
        f"- Test accuracy {test_metrics['accuracy']:.1%}; macro-F1 {test_metrics['macro_f1']:.3f}."
    )
with right:
    st.markdown("**Still needs validation**")
    st.write(
        "- Sentiment against independently human-labeled text.\n"
        "- Candidate issue-tag precision/recall against completed annotations.\n"
        "- Whether reviewer patterns indicate anything beyond unusual activity."
    )

if AUDIT_PATH.is_file():
    try:
        annotations = pd.read_csv(AUDIT_PATH, usecols=["human_tags"], keep_default_na=False)
        annotated = int(annotations["human_tags"].astype(str).str.strip().ne("").sum())
        total = len(annotations)
        st.caption(
            f"Issue-tag audit status: {annotated:,} of {total:,} primary labels complete. "
            "No population precision estimate is displayed until all sampled labels are finished."
        )
    except (OSError, ValueError, pd.errors.ParserError) as error:
        st.error(f"Could not read the local issue audit status: {error}")
